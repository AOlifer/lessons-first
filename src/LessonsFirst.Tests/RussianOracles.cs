    /// <summary>Поиск леммы и номера колонки по словоформе в независимой таблице.</summary>
    internal static (string Lemma, NumberRu Number)? FindNounForm(string form)
    {
        foreach (var (lemma, forms) in NounParadigms)
        {
            for (var i = 0; i < 12; i++)
            {
                if (forms[i] == form)
                {
                    return (lemma, i < 6 ? NumberRu.Singular : NumberRu.Plural);
                }
            }
        }

        return null;
    }

    /// <summary>Поиск (лемма, число) по словоформе В ДАННОМ ПАДЕЖЕ:
    /// разрешает неоднозначность вроде «леса» (род. ед. = им. мн.).</summary>
    internal static List<(string Lemma, NumberRu Number)> FindNounFormInCase(string form, CaseRu c)
    {
        var result = new List<(string, NumberRu)>();
        foreach (var (lemma, forms) in NounParadigms)
        {
            if (forms[(int)c] == form)
            {
                result.Add((lemma, NumberRu.Singular));
            }

            if (forms[6 + (int)c] == form)
            {
                result.Add((lemma, NumberRu.Plural));
            }
        }

        return result;
    }

    /// <summary>Форма прилагательного из независимой таблицы окончаний.</summary>
    internal static string AdjectiveForm(string lemma, Gender gender, NumberRu number, CaseRu c)
    {
        var (stem, soft) = Adjectives[lemma];
        // Порядок окончаний — по enum CaseRu (Им, Род, Дат, Вин, Твор, Пред), по 6 элементов.
        string[] endings = (gender, number, soft) switch
        {
            (_, NumberRu.Plural, false) => new[] { "ые", "ых", "ым", "ые", "ыми", "ых" },
            (_, NumberRu.Plural, true) => new[] { "ие", "их", "им", "ие", "ими", "их" },
            (Gender.Masculine, _, false) => new[] { "ый", "ого", "ому", "ый", "ым", "ом" },
            (Gender.Masculine, _, true) => new[] { "ий", "его", "ему", "ий", "им", "ем" },
            (Gender.Feminine, _, false) => new[] { "ая", "ой", "ой", "ую", "ой", "ой" },
            (Gender.Feminine, _, true) => new[] { "яя", "ей", "ей", "юю", "ей", "ей" },
            (_, _, false) => new[] { "ое", "ого", "ому", "ое", "ым", "ом" },
            _ => new[] { "ее", "его", "ему", "ее", "им", "ем" },
        };

        return stem + endings[(int)c];
    }
